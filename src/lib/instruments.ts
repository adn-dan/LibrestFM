const COL: Record<"fr" | "es" | "de" | "it" | "pt", number> = { fr: 0, es: 1, de: 2, it: 3, pt: 4 };

/** « drums (drum set), percussion » → « batterie, percussions » (selon la langue). */
export function translateDetail(detail: string, lang: Lang): string {
  if (lang === "en") return detail;
  const cjk = lang === "zh" || lang === "ja";
  const tr = (part: string) => {
    const k = part.toLowerCase();
    return lang === "zh" || lang === "ja" ? CJK[k]?.[lang === "zh" ? 0 : 1] : T[k]?.[COL[lang]];
  };
  return detail
    .split(/,\s*/)
    .map((part) => tr(part) ?? part)
    .join(cjk ? "、" : ", ");
}
